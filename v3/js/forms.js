//   lf/rf 脚：{x,z,yaw,lift,pitch}（pitch>0 脚尖翘起，<0 脚跟离地）
//   w 重心（0=全在左脚，1=全在右脚）  h 下蹲量  yaw 胯朝向  waist 转腰  lean 前倾
