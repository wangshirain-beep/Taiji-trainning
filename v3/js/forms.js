  const DEG = Math.PI / 180;
  const DIRS = { F: [0, 0, 1], B: [0, 0, -1], U: [0, 1, 0], D: [0, -1, 0], L: [-1, 0, 0], R: [1, 0, 0] };

  function V(str) {
    const v = [0, 0, 0];
    for (const ch of str) for (let i = 0; i < 3; i++) v[i] += DIRS[ch][i];
    const n = Math.hypot(v[0], v[1], v[2]) || 1;
    return v.map((x) => x / n);
  }
  function H(r, u, f, palm, fin, kind) { return { p: [r, u, f], palm: V(palm), fin: V(fin), kind: kind || 'palm' }; }
  function F(pt, yaw, extra) { return Object.assign({ x: pt.x, z: pt.z, yaw, lift: 0, pitch: 0 }, extra || {}); }
  // 以 ref 为基准、朝向 Y 度时，向前 f 米、向左 l 米的位置
  function at(ref, Y, f, l) {
    const s = Math.sin(Y * DEG), c = Math.cos(Y * DEG);
    return { x: ref.x + f * s + l * c, z: ref.z + f * c - l * s };
  }
  function clonePose(p) {
    return {
      lf: { ...p.lf }, rf: { ...p.rf }, lh: p.lh, rh: p.rh,
      w: p.w, h: p.h, yaw: p.yaw, waist: p.waist, lean: p.lean, look: p.look,
    };
  }

