  class Seq {
    constructor(start) {
      this.cur = clonePose(start);
      this.keys = [{ t: 0, say: null, pose: clonePose(start), form: -1 }];
      this.form = -1;
    }
    L() { return this.cur.lf; }
    R() { return this.cur.rf; }
    k(t, say, ch) {
      const c = this.cur;
      for (const key of Object.keys(ch || {})) {
        if (key === 'lf' || key === 'rf') c[key] = Object.assign({ ...c[key] }, ch[key]);
        else c[key] = ch[key];
      }
      this.keys.push({ t, say, pose: clonePose(c), form: this.form });
    }
  }

